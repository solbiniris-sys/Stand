// romance.js — 관계성에 따른 엔딩 판정. 서버/네트워크와 분리된 순수 함수라서 따로 테스트할 수 있다.
//
// 판정 재료
//   confessed : '이름 붙이기' 를 겪었는가 (고백 여부)
//   rom       : rom:1 표시가 붙은 사건을 몇 개 겪었는가 (함께 쌓은 설렘)
//   bond      : 마지막 장 끝의 유대
//   memories  : 앨범에 남은 추억 수
//
// 엔딩 4종 (위에서부터 먼저 맞는 것)
//   promise  : 고백 + 설렘 8개 이상 + 유대 95 이상  → "같은 골목, 같은 이름"
//   named    : 고백 완료                              → "이름이 붙은 봄"
//   unspoken : 고백 없이 유대 75 이상                 → "아직 말하지 못한 단어"
//   alley    : 그 외                                  → "여전히 같은 골목"
module.exports = (D, E) => {
  const NAME_ID = '3:이름 붙이기';

  const stats = r => ({
    confessed: r.done.includes(NAME_ID),
    rom: r.done.filter(id => E.byId[id] && E.byId[id].rom).length,
    bond: r.bond,
    memories: (r.album || []).length,
  });

  const ending = r => {
    const s = stats(r);
    let id;
    if (s.confessed && s.rom >= 8 && s.bond >= 95) id = 'promise';
    else if (s.confessed) id = 'named';
    else if (s.bond >= 75) id = 'unspoken';
    else id = 'alley';
    return { id, ...TEXT[id], stats: s };
  };

  // 엔딩 문장은 {N}{J} 와 조사 표기를 쓴다 (server 의 fill 이 보정)
  const TEXT = {
    promise: {
      title: '같은 골목, 같은 이름',
      lines: [
        '다시 여름이 온다. 나기네 아이스박스가 일식집 문 앞에 놓이는 날, {J}은(는) 이제 들뜬 것을 숨기지 않는다.',
        '병 속의 별은 하나씩 열렸고, 마지막 하나만 아직 닫혀 있다. 열 필요가 없다는 것을 두 사람 다 안다.',
        '"내년 이맘때엔 뭐 하고 있을까." 그 질문에 대한 대답이 이제는 질문보다 먼저 와 있다.',
        '이름 붙이지 않아도 알던 사이는, 이름이 붙은 뒤에도 그대로였다. 같은 골목에서, 이번에는 나란히.',
      ],
    },
    named: {
      title: '이름이 붙은 봄',
      lines: [
        '벚꽃이 지고 나서도 두 사람은 같은 길로 퇴근한다. 달라진 것은 손의 위치뿐이다.',
        '{J}의 가게에는 가끔 이유 없이 두 사람분의 자리가 비어 있다. 단골 아주머니는 그 자리를 보며 아무 말 없이 웃는다.',
        '아직 하지 못한 이야기도, 아직 가 보지 못한 곳도 많다. 그래도 그것들은 이제 "나중에"가 아니라 "같이"의 몫이다.',
      ],
    },
    unspoken: {
      title: '아직 말하지 못한 단어',
      lines: [
        '가게 앞에서 마주 서는 일이 일상이 되었다. 말하지 않은 단어는 여전히 입속에서 굴러다닌다.',
        '그래도 {N}이(가) 걸음을 늦추면 {J}이(가) 멈춰 서는 것을, 두 사람은 이미 알고 있다.',
        '이름이 없어도 이어지는 사이. 언젠가 누군가 먼저 말하게 될 날을, 골목이 천천히 기다린다.',
      ],
      hint: '유대는 충분했지만 마음을 말로 옮기지 못했다. 다음에는 "이름 붙이기"가 열리는 때를 놓치지 말아 보세요.',
    },
    alley: {
      title: '여전히 같은 골목',
      lines: [
        '해산물 상자는 여전히 나기네에서 준야네로 건너간다. 두 사람은 같은 골목에서, 같은 계절을 지나왔다.',
        '아직은 이름을 붙이기엔 조금 이른 사이일지도 모른다. 하지만 이 골목에는 앞으로 쌓일 날이 아직 많이 남아 있다.',
      ],
      hint: '이야기는 계속된다. 더 머물며 유대를 쌓으면 다른 결말이 열릴 수 있어요.',
    },
  };

  return { ending, stats, TEXT };
};
